import requests
import hashlib
import json
import getpass
from datetime import datetime, timezone
from pathlib import Path

import psycopg
from psycopg.types.json import Jsonb
from shapely.geometry import LineString, Polygon
from shapely import wkt

ROOT = Path(r"D:\ZIAD WEB ITI\The_Digital_Dark_Economy")
ENDPOINT = "https://maps.mail.ru/osm/tools/overpass/api/interpreter"

print("1. Preparing OSM roads and buildings extraction...")

query = """
[out:json][timeout:180];
(
  way["highway"](29.95,31.15,30.15,31.45);
  way["building"](29.95,31.15,30.15,31.45);
);
out geom;
"""

response = requests.post(
    ENDPOINT,
    data={"data": query},
    timeout=(30, 300),
    headers={"User-Agent": "DigitalDarkEconomyCairoPilot/1.0 (research project)"}
)
response.raise_for_status()

raw_bytes = response.content
payload = response.json()
checksum = hashlib.sha256(raw_bytes).hexdigest()
retrieved = datetime.now(timezone.utc).isoformat()

print("OSM response received.")
print("Elements:", len(payload.get("elements", [])))
print("SHA256:", checksum)

print("\n2. Converting OSM geometries...")

features = []
roads = 0
buildings = 0
skipped = 0

for item in payload.get("elements", []):
    if item.get("type") != "way":
        continue

    tags = item.get("tags", {})
    coords = item.get("geometry", [])

    if len(coords) < 2:
        skipped += 1
        continue

    points = [(p["lon"], p["lat"]) for p in coords]

    try:
        if tags.get("highway"):
            geom = LineString(points)
            feature_type = "road"
            roads += 1

        elif tags.get("building"):
            if len(points) < 4 or points[0] != points[-1]:
                skipped += 1
                continue

            geom = Polygon(points)

            if not geom.is_valid:
                geom = geom.buffer(0)

            if geom.is_empty or geom.geom_type not in ("Polygon", "MultiPolygon"):
                skipped += 1
                continue

            feature_type = "building"
            buildings += 1

        else:
            continue

        if geom.is_empty:
            skipped += 1
            continue

        features.append((
            f"way/{item['id']}",
            feature_type,
            json.dumps(tags, ensure_ascii=False),
            geom.wkt
        ))

    except Exception:
        skipped += 1

print("Roads:", roads)
print("Buildings:", buildings)
print("Skipped:", skipped)

if not features:
    raise RuntimeError("No usable OSM spatial features were extracted.")

print("\n3. Connecting to PostgreSQL...")
password = getpass.getpass("PostgreSQL password: ")

with psycopg.connect(
    host="127.0.0.1",
    port=5432,
    dbname="digital_dark_economy",
    user="postgres",
    password=password
) as conn:

    with conn.cursor() as cur:

        cur.execute("""
            SELECT COUNT(*)
            FROM model_run
            WHERE run_name = 'OSM + WorldPop + Roads & Buildings Cairo'
        """)

        if cur.fetchone()[0]:
            raise RuntimeError(
                "The third run already exists. Stopping to prevent duplicates."
            )

        cur.execute("""
            CREATE TABLE IF NOT EXISTS raw_spatial_feature (
                feature_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                source_id BIGINT NOT NULL REFERENCES source_dataset(source_id),
                source_record_id TEXT NOT NULL,
                feature_type VARCHAR(30) NOT NULL
                    CHECK (feature_type IN ('road', 'building')),
                tags JSONB NOT NULL DEFAULT '{}'::JSONB,
                geom GEOMETRY(Geometry, 4326) NOT NULL,
                retrieved_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                UNIQUE (source_id, source_record_id)
            )
        """)

        cur.execute("""
            CREATE INDEX IF NOT EXISTS idx_raw_spatial_geom
            ON raw_spatial_feature USING GIST (geom)
        """)

        cur.execute("""
            CREATE INDEX IF NOT EXISTS idx_raw_spatial_type
            ON raw_spatial_feature (feature_type)
        """)

        cur.execute("""
            INSERT INTO source_dataset
                (name, provider, licence, release_id, url, checksum)
            VALUES (%s, %s, %s, %s, %s, %s)
            RETURNING source_id
        """, (
            "OpenStreetMap Roads and Buildings",
            "Overpass API",
            "ODbL",
            retrieved,
            ENDPOINT,
            checksum
        ))

        source_id = cur.fetchone()[0]

        print("Saving raw spatial features...")

        batch = []

        for record_id, feature_type, tags, geometry in features:
            batch.append((
                source_id,
                record_id,
                feature_type,
                Jsonb(json.loads(tags)),
                geometry
            ))

            if len(batch) >= 1000:
                cur.executemany("""
                    INSERT INTO raw_spatial_feature
                        (source_id, source_record_id, feature_type, tags, geom)
                    VALUES
                        (%s, %s, %s, %s, ST_SetSRID(ST_GeomFromText(%s),4326))
                    ON CONFLICT (source_id, source_record_id) DO NOTHING
                """, batch)
                batch.clear()

        if batch:
            cur.executemany("""
                INSERT INTO raw_spatial_feature
                    (source_id, source_record_id, feature_type, tags, geom)
                VALUES
                    (%s, %s, %s, %s, ST_SetSRID(ST_GeomFromText(%s),4326))
                ON CONFLICT (source_id, source_record_id) DO NOTHING
            """, batch)

        conn.commit()

        print("Raw spatial data committed successfully.")

        cur.execute("""
            SELECT run_id, project_id
            FROM model_run
            WHERE run_name = 'OSM + WorldPop Cairo 2025'
              AND status = 'completed'
            ORDER BY run_id DESC
            LIMIT 1
        """)

        previous = cur.fetchone()

        if not previous:
            raise RuntimeError("Completed WorldPop run not found.")

        previous_id, project_id = previous

        cur.execute("""
            INSERT INTO model_run
                (project_id, run_name, algorithm_version,
                 status, parameters, notes)
            VALUES (%s, %s, %s, 'running', %s, %s)
            RETURNING run_id
        """, (
            project_id,
            "OSM + WorldPop + Roads & Buildings Cairo",
            "osm-worldpop-roads-buildings-v1",
            Jsonb({
                "h3_resolution": 8,
                "population_year": 2025,
                "spatial_source_id": source_id,
                "road_measurement": "clipped length in UTM zone 36N",
                "building_measurement": "building point-on-surface assigned to H3 cell"
            }),
            "Separate run preserving the WorldPop run. "
            "Roads and building footprints extracted from OSM ways only. "
            "OSM completeness is not independently verified."
        ))

        run_id = cur.fetchone()[0]

        cur.execute("""
            INSERT INTO cell_features
                (h3_index, run_id, standard_category,
                 poi_count, competitor_count, population_estimate,
                 road_length_km, building_count)
            SELECT
                h3_index, %s, standard_category,
                poi_count, competitor_count, population_estimate,
                NULL, NULL
            FROM cell_features
            WHERE run_id = %s
            ON CONFLICT (h3_index, run_id, standard_category)
            DO NOTHING
        """, (run_id, previous_id))

        print("Calculating road length and building counts in small batches...")

        cur.execute(
            "SELECT h3_index::text, ST_AsText(geom) "
            "FROM h3_cell ORDER BY h3_index"
        )
        cells = cur.fetchall()
        total_cells = len(cells)

        for index, (h3_value, cell_wkt) in enumerate(cells, start=1):
            cell_expression = "ST_SetSRID(ST_GeomFromText(%s), 4326)"

            cur.execute(f'''
                SELECT COALESCE(
                    SUM(
                        ST_Length(
                            ST_Transform(
                                ST_Intersection(r.geom, cell.geom),
                                32636
                            )
                        )
                    ), 0
                ) / 1000.0
                FROM raw_spatial_feature r
                CROSS JOIN (
                    SELECT {cell_expression} AS geom
                ) cell
                WHERE r.feature_type = 'road'
                  AND r.geom && cell.geom
                  AND ST_Intersects(r.geom, cell.geom)
            ''', (cell_wkt,))

            road_km = cur.fetchone()[0]

            cur.execute(f'''
                SELECT COUNT(*)
                FROM raw_spatial_feature b
                CROSS JOIN (
                    SELECT {cell_expression} AS geom
                ) cell
                WHERE b.feature_type = 'building'
                  AND b.geom && cell.geom
                  AND ST_Covers(cell.geom, ST_PointOnSurface(b.geom))
            ''', (cell_wkt,))

            building_count = cur.fetchone()[0]

            cur.execute(
                "UPDATE cell_features SET road_length_km = %s, "
                "building_count = %s, calculated_at = NOW() "
                "WHERE h3_index = %s::h3index AND run_id = %s",
                (road_km, building_count, h3_value, run_id)
            )

            if index % 25 == 0:
                conn.commit()
                print(f"Processed {index}/{total_cells} H3 cells...")

        conn.commit()
        print(f"Completed spatial calculations for {total_cells} H3 cells.")

        cur.execute("""
            UPDATE model_run
            SET status = 'completed',
                completed_at = NOW()
            WHERE run_id = %s
        """, (run_id,))

        cur.execute("""
            SELECT
                COUNT(DISTINCT h3_index),
                COUNT(*),
                COUNT(road_length_km),
                COUNT(building_count),
                ROUND(MAX(road_length_km), 4),
                MAX(building_count)
            FROM cell_features
            WHERE run_id = %s
        """, (run_id,))

        stats = cur.fetchone()

        cur.execute("""
            SELECT
                COUNT(*) FILTER (WHERE feature_type = 'road'),
                COUNT(*) FILTER (WHERE feature_type = 'building')
            FROM raw_spatial_feature
            WHERE source_id = %s
        """, (source_id,))

        saved = cur.fetchone()

    conn.commit()

print("\n========== SPATIAL INTEGRATION SUCCESS ==========")
print("Source ID:", source_id)
print("Previous run:", previous_id)
print("New run:", run_id)
print("Saved roads:", saved[0])
print("Saved buildings:", saved[1])
print("H3 cells:", stats[0])
print("Feature rows:", stats[1])
print("Rows with road length:", stats[2])
print("Rows with building count:", stats[3])
print("Maximum road length (km):", stats[4])
print("Maximum buildings in one cell:", stats[5])
print("=================================================")



