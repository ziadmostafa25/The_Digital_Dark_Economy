
BEGIN;

-- 1. H3 spatial cells
CREATE TABLE public.h3_cell (
    h3_index h3index PRIMARY KEY,
    resolution SMALLINT NOT NULL CHECK (resolution BETWEEN 0 AND 15),
    geom GEOMETRY(Polygon, 4326) NOT NULL,
    centroid GEOMETRY(Point, 4326),
    area_sq_km NUMERIC(14,6) CHECK (area_sq_km IS NULL OR area_sq_km > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Client projects
CREATE TABLE public.client_project (
    project_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_name VARCHAR(200) NOT NULL,
    client_name VARCHAR(200),
    description TEXT,
    study_area GEOMETRY(MultiPolygon, 4326),
    target_categories JSONB NOT NULL DEFAULT '[]'::JSONB,
    status VARCHAR(30) NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft', 'active', 'completed', 'archived')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Analysis runs
CREATE TABLE public.model_run (
    run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT REFERENCES public.client_project(project_id),
    run_name VARCHAR(200) NOT NULL,
    algorithm_version VARCHAR(50),
    status VARCHAR(30) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'running', 'completed', 'failed')),
    parameters JSONB NOT NULL DEFAULT '{}'::JSONB,
    started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    completed_at TIMESTAMPTZ,
    notes TEXT,
    CHECK (completed_at IS NULL OR completed_at >= started_at)
);

-- 4. Features per H3 cell
CREATE TABLE public.cell_features (
    feature_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    h3_index h3index NOT NULL REFERENCES public.h3_cell(h3_index),
    run_id BIGINT NOT NULL REFERENCES public.model_run(run_id),
    standard_category VARCHAR(100) NOT NULL,
    poi_count INTEGER NOT NULL DEFAULT 0 CHECK (poi_count >= 0),
    competitor_count INTEGER NOT NULL DEFAULT 0 CHECK (competitor_count >= 0),
    population_estimate NUMERIC(14,2)
        CHECK (population_estimate IS NULL OR population_estimate >= 0),
    road_length_km NUMERIC(14,4)
        CHECK (road_length_km IS NULL OR road_length_km >= 0),
    building_count INTEGER
        CHECK (building_count IS NULL OR building_count >= 0),
    calculated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_cell_features_run_category
        UNIQUE (h3_index, run_id, standard_category)
);

-- 5. Data completeness estimates
CREATE TABLE public.completeness_estimate (
    completeness_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    h3_index h3index NOT NULL REFERENCES public.h3_cell(h3_index),
    source_id BIGINT NOT NULL REFERENCES public.source_dataset(source_id),
    run_id BIGINT NOT NULL REFERENCES public.model_run(run_id),
    standard_category VARCHAR(100) NOT NULL,
    observed_count INTEGER NOT NULL DEFAULT 0 CHECK (observed_count >= 0),
    estimated_completeness NUMERIC(5,4)
        CHECK (estimated_completeness BETWEEN 0 AND 1),
    confidence NUMERIC(5,4)
        CHECK (confidence BETWEEN 0 AND 1),
    estimation_method VARCHAR(100),
    limitations TEXT,
    estimated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_completeness_cell_source_run
        UNIQUE (h3_index, source_id, run_id, standard_category)
);

-- 6. Opportunity and service gap scores
CREATE TABLE public.gap_score (
    gap_score_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    h3_index h3index NOT NULL REFERENCES public.h3_cell(h3_index),
    run_id BIGINT NOT NULL REFERENCES public.model_run(run_id),
    standard_category VARCHAR(100) NOT NULL,
    opportunity_score NUMERIC(6,2) NOT NULL
        CHECK (opportunity_score BETWEEN 0 AND 100),
    demand_indicator NUMERIC(6,2)
        CHECK (demand_indicator BETWEEN 0 AND 100),
    competition_indicator NUMERIC(6,2)
        CHECK (competition_indicator BETWEEN 0 AND 100),
    coverage_indicator NUMERIC(6,2)
        CHECK (coverage_indicator BETWEEN 0 AND 100),
    data_confidence NUMERIC(5,4)
        CHECK (data_confidence BETWEEN 0 AND 1),
    explanation JSONB NOT NULL DEFAULT '{}'::JSONB,
    calculated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_gap_score_cell_run_category
        UNIQUE (h3_index, run_id, standard_category)
);

-- 7. Field observations
CREATE TABLE public.field_observation (
    observation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT REFERENCES public.client_project(project_id),
    h3_index h3index REFERENCES public.h3_cell(h3_index),
    poi_id BIGINT REFERENCES public.poi_entity(poi_id),
    observed_category VARCHAR(100) NOT NULL,
    observation_type VARCHAR(50) NOT NULL,
    observed_value TEXT,
    geom GEOMETRY(Point, 4326),
    observer_ref VARCHAR(100),
    observed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    notes TEXT,
    CHECK (h3_index IS NOT NULL OR poi_id IS NOT NULL OR geom IS NOT NULL)
);

-- Spatial indexes
CREATE INDEX idx_h3_cell_geom
    ON public.h3_cell USING GIST (geom);

CREATE INDEX idx_h3_cell_centroid
    ON public.h3_cell USING GIST (centroid);

CREATE INDEX idx_client_project_area
    ON public.client_project USING GIST (study_area);

CREATE INDEX idx_field_observation_geom
    ON public.field_observation USING GIST (geom);

-- Analytical indexes
CREATE INDEX idx_cell_features_category
    ON public.cell_features (standard_category);

CREATE INDEX idx_completeness_source
    ON public.completeness_estimate (source_id);

CREATE INDEX idx_gap_score_ranking
    ON public.gap_score (run_id, standard_category, opportunity_score DESC);

CREATE INDEX idx_model_run_project
    ON public.model_run (project_id);

CREATE INDEX idx_field_observation_project
    ON public.field_observation (project_id);

COMMIT;
